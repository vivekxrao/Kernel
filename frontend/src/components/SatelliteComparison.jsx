import React, { useEffect, useState } from 'react';
import { AlertTriangle, LoaderCircle, RefreshCw, Satellite, SlidersHorizontal } from 'lucide-react';
import { MapContainer, Pane, TileLayer } from 'react-leaflet';
import { getLayers } from '../lib/api.js';

export default function SatelliteComparison() {
  const [layers, setLayers] = useState(null);
  const [reveal, setReveal] = useState(50);
  const [showDamage, setShowDamage] = useState(true);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  async function load() {
    setLoading(true);
    setError('');
    try {
      setLayers(await getLayers());
    } catch (e) {
      setError(e.message || 'Could not load Earth Engine map layers.');
    } finally {
      setLoading(false);
    }
  }
  useEffect(() => { load(); }, []);

  return <section className="kd-page-section">
    <div className="kd-page-heading-row">
      <div><div className="kd-eyebrow">SENTINEL-1 / TEMPORAL CHANGE</div><h1>Satellite Comparison</h1><p>Drag the divider to reveal the inference-period SAR composite and PWTT change layer.</p></div>
      <button className="kd-secondary-btn" onClick={load} disabled={loading}><RefreshCw size={15}/>{loading ? 'Loading layers' : 'Reload imagery'}</button>
    </div>
    <div className="kd-panel kd-comparison-panel">
      <div className="kd-panel-title"><div><h2><Satellite size={18}/> Before / After reveal</h2><p>Bakhmut, Ukraine · matching AOI and map projection</p></div><span className="kd-data-pill">EARTH ENGINE</span></div>
      {loading && <div className="kd-loading"><LoaderCircle className="kd-spin" size={24}/> Requesting Sentinel-1 map tiles from Google Earth Engine…</div>}
      {error && <div className="kd-alert"><AlertTriangle size={17}/><div><b>Satellite imagery unavailable</b><small>{error}</small><small>Check Earth Engine authentication, project access and Sentinel-1 availability.</small></div></div>}
      {layers && !loading && <>
        <div className="kd-comparison-labels"><span>BEFORE · {layers.dates.before_start} — {layers.dates.before_end}</span><span>INFERENCE · {layers.dates.inference_start} — {layers.dates.inference_end}</span></div>
        <div className="kd-reveal-map">
          <MapContainer center={[48.59, 37.99]} zoom={13} scrollWheelZoom className="kd-leaflet-map">
            <Pane name="beforePane" style={{ zIndex: 410 }}>
              <TileLayer url={layers.before} attribution="Sentinel-1 · Google Earth Engine" />
            </Pane>
            <Pane name="afterPane" style={{ zIndex: 420, clipPath: `inset(0 0 0 ${reveal}%)` }}>
              <TileLayer url={layers.after} />
            </Pane>
            {showDamage && <Pane name="pwttPane" style={{ zIndex: 430, clipPath: `inset(0 0 0 ${reveal}%)` }}>
              <TileLayer url={layers.damage} opacity={0.62} />
            </Pane>}
          </MapContainer>
          <div className="kd-reveal-divider" style={{ left: `${reveal}%` }}><span>↔</span></div>
          <div className="kd-reveal-hint left">BEFORE</div><div className="kd-reveal-hint right">AFTER + PWTT</div>
        </div>
        <div className="kd-slider-controls">
          <div className="kd-slider-meta"><span><SlidersHorizontal size={15}/> Drag to reveal</span><b>{reveal}%</b></div>
          <input aria-label="Before after reveal position" type="range" min="0" max="100" value={reveal} onChange={(e) => setReveal(Number(e.target.value))}/>
          <div className="kd-slider-actions"><label><input type="checkbox" checked={showDamage} onChange={(e) => setShowDamage(e.target.checked)}/> Show PWTT T-statistic overlay</label><button className="kd-secondary-btn" onClick={() => setReveal(50)}>Reset divider</button></div>
        </div>
        <div className="kd-method-note"><b>Interpretation note:</b> Before/after are median Sentinel-1 SAR context composites over the configured periods. The PWTT overlay is generated by the installed PWTT package; a high score is a change indicator, not proof of physical damage.</div>
        {layers.note && <p className="kd-comparison-footnote">{layers.note}</p>}
      </>}
    </div>
  </section>;
}
